-- Supabase → SQL Editor → New query → shu kodni joylab "Run" bosing.
-- Bir necha marta ishga tushirilsa ham xavfsiz.
--
-- Qanday ishlatiladi:
--   • Ko'rish:  Table Editor → "balances" (har mijoz: to'ldirgan, sarflagan, qo'lda, balans).
--   • Qo'shish: Table Editor → "balance_adjustments" → Insert row:
--       telegram_user_id = mijoz ID si ("balances" dan oling)
--       amount           = 5000  (qo'shish)  yoki  -5000  (ayirish)
--       note             = sabab (ixtiyoriy, masalan "sovg'a", "xato to'lov qaytarildi")
--     Bot va ilova balansni darhol yangisini ko'rsatadi.
--   • Bekor qilish: noto'g'ri qatorni o'chirmang — teskari summali yangi qator qo'shing
--     (tarix saqlansin).

-- Egasining qo'lda tuzatishlari
create table if not exists balance_adjustments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  telegram_user_id bigint not null,
  amount numeric not null check (amount <> 0),
  note text
);
create index if not exists balance_adjustments_user_idx on balance_adjustments (telegram_user_id);
alter table balance_adjustments enable row level security;

-- Raqamga xavfsiz aylantirish (JS dagi Number(x) || 0 kabi)
create or replace function bal_num(v text) returns numeric
language sql immutable as $$
  select case when v ~ '^\s*-?[0-9]+(\.[0-9]+)?\s*$' then v::numeric else 0 end
$$;

-- Har mijozning balansi — api/_lib/balance.js dagi sumOf bilan bir xil hisob:
--   + to'ldirish (details.topup va details.payment bor) -> payment.amount
--   - details.spent (bekor qilingan buyurtmalardan tashqari)
--   ± balance_adjustments
-- security_invoker: ko'rinish RLS ni chetlab o'tmaydi (ochiq kalit bilan o'qib bo'lmaydi).
create or replace view balances with (security_invoker = true) as
with o as (
  select telegram_user_id,
    sum(case when coalesce(details->>'topup', '') not in ('', '0', 'false')
              and jsonb_typeof(details->'payment') = 'object'
             then bal_num(details->'payment'->>'amount') else 0 end) as toldirgan,
    sum(case when coalesce(details->>'spent', '') not in ('', '0', 'false')
              and status <> 'cancelled'
             then bal_num(details->>'spent') else 0 end) as sarflagan
  from orders
  where telegram_user_id is not null
  group by telegram_user_id
),
a as (
  select telegram_user_id, sum(amount) as qolda
  from balance_adjustments
  group by telegram_user_id
),
ids as (
  select telegram_user_id from o
  union
  select telegram_user_id from a
)
select
  ids.telegram_user_id,
  u.first_name as ism,
  u.username,
  coalesce(o.toldirgan, 0) as toldirgan,
  coalesce(o.sarflagan, 0) as sarflagan,
  coalesce(a.qolda, 0) as qolda,
  coalesce(o.toldirgan, 0) - coalesce(o.sarflagan, 0) + coalesce(a.qolda, 0) as balans
from ids
left join o on o.telegram_user_id = ids.telegram_user_id
left join a on a.telegram_user_id = ids.telegram_user_id
left join users u on u.telegram_user_id = ids.telegram_user_id
where coalesce(o.toldirgan, 0) <> 0 or coalesce(o.sarflagan, 0) <> 0 or coalesce(a.qolda, 0) <> 0
order by balans desc;
